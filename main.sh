# =============================================================================
# Constantes
# =============================================================================

readonly EXIT_SUCCESS=0
readonly EXIT_ERROR=1

# =============================================================================
# Variáveis Globais
# =============================================================================

readonly PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly BOOTSTRAP_FILE="${PROJECT_ROOT}/bootstrap.sh"

# =============================================================================
# Funções Privadas
# =============================================================================

# -----------------------------------------------------------------------------
# Exibe um erro fatal e encerra a aplicação
# -----------------------------------------------------------------------------
fatal() {

    local message="$1"

    printf '\n[ERRO] %s\n' "${message}" >&2
    exit "${EXIT_ERROR}"
}

# -----------------------------------------------------------------------------
# Valida a existência do bootstrap
# -----------------------------------------------------------------------------
validate_bootstrap() {

    [[ -r "${BOOTSTRAP_FILE}" ]] ||
        fatal "Arquivo bootstrap.sh não encontrado: ${BOOTSTRAP_FILE}"
}

# -----------------------------------------------------------------------------
# Carrega o bootstrap da aplicação
# -----------------------------------------------------------------------------
start_application() {

    # shellcheck source=bootstrap.sh
    source "${BOOTSTRAP_FILE}"
}

# =============================================================================
# Funções Públicas
# =============================================================================

# -----------------------------------------------------------------------------
# Fluxo principal da aplicação
# -----------------------------------------------------------------------------
main() {

    validate_bootstrap

    start_application

    return "${EXIT_SUCCESS}"
}

main "$@"
