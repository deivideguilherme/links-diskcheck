# -----------------------------------------------------------------------------
# Verifica se o argumento informado não está vazio.
# -----------------------------------------------------------------------------
is_non_empty()
{
    [[ "$#" -eq 1 ]] || return 1
    [[ -n "$1" ]]
}

# -----------------------------------------------------------------------------
# Verifica se o argumento informado representa um número inteiro.
# -----------------------------------------------------------------------------
is_integer()
{
    [[ "$#" -eq 1 ]] || return 1
    [[ "$1" =~ ^-?[0-9]+$ ]]
}

# -----------------------------------------------------------------------------
# Verifica se o argumento informado representa um inteiro positivo.
# -----------------------------------------------------------------------------
is_positive_integer()
{
    [[ "$#" -eq 1 ]] || return 1
    [[ "$1" =~ ^[1-9][0-9]*$ ]]
}

# -----------------------------------------------------------------------------
# Verifica se o argumento informado corresponde a um caminho existente.
# -----------------------------------------------------------------------------
is_valid_path()
{
    [[ "$#" -eq 1 ]] || return 1
    [[ -e "$1" ]]
}
